import sqlite3

import click
from flask import current_app, g
from flask.cli import with_appcontext


class Connection:
    """Thin wrapper so the rest of the app can use '?' placeholders and a
    uniform execute()/commit() API on both SQLite and PostgreSQL."""

    def __init__(self, raw, backend):
        self.raw = raw
        self.backend = backend

    def execute(self, sql, params=()):
        if self.backend == "postgres":
            sql = sql.replace("?", "%s")
        cursor = self.raw.cursor()
        cursor.execute(sql, params)
        return cursor

    def commit(self):
        self.raw.commit()

    def close(self):
        self.raw.close()


def _database_url():
    return current_app.config.get("DATABASE_URL")


def get_db():
    if "db" not in g:
        url = _database_url()
        if url:
            import psycopg2
            import psycopg2.extras

            raw = psycopg2.connect(url, cursor_factory=psycopg2.extras.RealDictCursor)
            g.db = Connection(raw, "postgres")
        else:
            raw = sqlite3.connect(current_app.config["DATABASE"])
            raw.row_factory = sqlite3.Row
            raw.execute("PRAGMA foreign_keys = ON")
            g.db = Connection(raw, "sqlite")
    return g.db


def close_db(exception=None):
    db = g.pop("db", None)
    if db is not None:
        db.close()


def _schema():
    if _database_url():
        pk = "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    else:
        pk = "INTEGER PRIMARY KEY AUTOINCREMENT"
    return f"""
CREATE TABLE IF NOT EXISTS users (
    id {pk},
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'CUSTOMER',
    two_factor_secret TEXT,
    two_factor_enabled INTEGER NOT NULL DEFAULT 0,
    recovery_codes TEXT,
    reset_token_hash TEXT,
    reset_token_expires TEXT,
    created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_users_reset_token ON users(reset_token_hash);
CREATE TABLE IF NOT EXISTS login_events (
    id {pk},
    user_id INTEGER,
    email TEXT,
    ip TEXT,
    user_agent TEXT,
    status TEXT NOT NULL,
    created_at TEXT NOT NULL,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_login_events_user ON login_events(user_id);
"""


def _run_script(db, script):
    for statement in script.split(";"):
        if statement.strip():
            db.execute(statement)


def init_db():
    db = get_db()
    _run_script(db, _schema())
    db.commit()


@click.command("init-db")
@with_appcontext
def init_db_command():
    """Create the database tables."""
    init_db()
    click.echo("Initialized the database.")


@click.command("clear-db")
@click.option("--yes", is_flag=True, help="Skip the confirmation prompt.")
@with_appcontext
def clear_db_command(yes):
    """Delete ALL data from the database (keeps the schema)."""
    if not yes:
        click.confirm("This deletes all data in the database. Continue?", abort=True)
    db = get_db()
    for table in ("login_events", "users"):
        db.execute(f"DROP TABLE IF EXISTS {table}")
    db.commit()
    init_db()
    click.echo("Cleared all data from the database.")


def init_app(app):
    app.teardown_appcontext(close_db)
    app.cli.add_command(init_db_command)
    app.cli.add_command(clear_db_command)
